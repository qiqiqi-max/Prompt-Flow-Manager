// 项目装配器「导出项目规则」的目标清单与内容生成。浏览器与 Node 测试共用。
//
// 这里只决定"渲染进程打算写哪些文件、写什么"。真正的落盘白名单在主进程的
// RULE_EXPORT_ALLOWED 里单独写死，不从这份清单 require——渲染进程被外部内容
// 劫持时，它能改的是这份文件在页面里的副本，改不了主进程的白名单。
// 两边会不会漂移由 npm test 盯着（每个 path 都必须在白名单里）。
//
// Cursor 新格式的文件名用固定的 project-rules.mdc，不从项目名派生：
// 一是白名单要的是固定路径集合，派生名就得放开成"某目录下任意 .mdc"；
// 二是改了项目名再导出一次，派生名会留下一份旧规则文件，Cursor 会把两份
// alwaysApply 规则一起注入，而且旧文件也就绕开了"已有文件先问再覆盖"那道保护。
const RULE_TARGETS = {
  // 顺序就是界面上的显示顺序，也是写盘顺序。
  list: [
    { id: 'claude', path: 'CLAUDE.md', hintKey: 'ruleTargetHintClaude' },
    { id: 'agents', path: 'AGENTS.md', hintKey: 'ruleTargetHintAgents' },
    { id: 'copilot', path: '.github/copilot-instructions.md', hintKey: 'ruleTargetHintCopilot' },
    { id: 'cursor-mdc', path: '.cursor/rules/project-rules.mdc', hintKey: 'ruleTargetHintCursorMdc' },
    { id: 'cursor-legacy', path: '.cursorrules', hintKey: 'ruleTargetHintCursorLegacy' }
  ],
  // 老版本固定导出这两份。没存过勾选状态的老用户必须照旧拿到它们，
  // 不能因为升级就多写或少写文件。
  defaultIds: ['claude', 'cursor-legacy'],

  // config.ruleExportTargets 的归一化。只有"从没存过"（不是数组）才回落默认值：
  // 用户明确全部取消勾选时存下的是 []，那是用户的选择，不能被默认值盖掉。
  // 认不出的 id 丢弃（将来删掉某个目标时，旧配置里的残留不会让导出报错）。
  normalizeIds(value) {
    if (!Array.isArray(value)) return RULE_TARGETS.defaultIds.slice();
    const wanted = new Set(value.filter(v => typeof v === 'string'));
    return RULE_TARGETS.list.filter(t => wanted.has(t.id)).map(t => t.id);
  },

  build(ids, projectName, body) {
    const name = String(projectName || 'Project Blueprint');
    const text = String(body || '');
    const chosen = new Set(RULE_TARGETS.normalizeIds(ids));
    const files = [];
    for (const target of RULE_TARGETS.list) {
      if (!chosen.has(target.id)) continue;
      files.push({ name: target.path, content: RULE_TARGETS.contentFor(target.id, name, text) });
    }
    return files;
  },

  contentFor(id, name, body) {
    if (id === 'cursor-mdc') {
      // Cursor 的 .mdc 规则：frontmatter 三个字段 description / globs / alwaysApply。
      // 装配器产出的是整个项目的总规约，所以是 Always 类型（alwaysApply: true，
      // globs 留空）——Cursor 自己在界面里新建 Always 规则时写出来的也是这个形状。
      //
      // description 用固定英文，不拼项目名：Cursor 的 frontmatter 不是完整 YAML 解析，
      // 项目名里的冒号、引号、# 都可能把这一行截断或解析坏，而这一行对 Always
      // 规则只是展示用，不值得为它做一套转义。
      return [
        '---',
        'description: Project engineering guidelines generated by Prompt Flow Manager',
        'globs:',
        'alwaysApply: true',
        '---',
        '',
        '# ' + name + ' - AI Engineering Guidelines',
        '',
        body
      ].join('\n');
    }
    if (id === 'cursor-legacy') return ['# Cursor Rules for ' + name, '', body].join('\n');
    if (id === 'copilot') return ['# ' + name + ' - Copilot Instructions', '', body].join('\n');
    return ['# ' + name + ' - AI Engineering Guidelines', '', body].join('\n');
  }
};

if (typeof module !== 'undefined' && module.exports) module.exports = RULE_TARGETS;
